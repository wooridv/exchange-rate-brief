def holiday_name(d):
    """d(date) 가 공휴일이면 이름, 아니면 None."""
    return KR_HOLIDAYS.get(d.strftime("%Y-%m-%d"))


def is_weekend(d):
    return d.weekday() >= 5  # 5=토, 6=일


def is_holiday(d):
    """주말 또는 법정/대체공휴일이면 True (브리핑 발송 제외 대상)."""
    return is_weekend(d) or (d.strftime("%Y-%m-%d") in KR_HOLIDAYS)


def skip_reason(d):
    """제외 사유 문자열(발송 안 하는 이유). 발송 가능일이면 None."""
    if is_weekend(d):
        return "주말(%s)" % ["월", "화", "수", "목", "금", "토", "일"][d.weekday()]
    name = holiday_name(d)
    if name:
        return "공휴일(%s)" % name
    return None
